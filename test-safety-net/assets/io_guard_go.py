def _top_level(pkg, table_group):
    """The top-level function names the filter marks under `pkg.`."""
    prefix = pkg + "."
    return [m[len(prefix):] for m in stack_go.UNCONTROLLABLE.get(table_group, ())
            + stack_go.CONTROLLABLE.get(table_group, ())
            if m.startswith(prefix) and "." not in m[len(prefix):]]


def _hook_targets():
    """[(package path, receiver type or None, name, group)], deduplicated, ordered."""
    t = [("syscall", None, n, SYSCALL_GROUPS[n]) for n in sorted(syscall_targets())]
    for group, spec in _UNIX_TARGETS.items():
        t += [("internal/syscall/unix", None, n, group) for n in _names(spec)]
    t += [("time", None, n, "clock") for n in _names(
        "Now Since Until After AfterFunc NewTimer NewTicker Tick Sleep")]
    t += [("math/rand", None, n, "randomness") for n in _top_level("math/rand", "randomness")]
    t += [("math/rand/v2", None, n, "randomness")
          for n in _top_level("math/rand/v2", "randomness")]
    t += [("crypto/rand", None, n, "randomness") for n in _names("Int Prime Read Text")]
    t += [("crypto/internal/sysrand", None, "Read", "randomness")]
    t += [("database/sql", None, n, "database") for n in _names("Open OpenDB")]
    t += [("net", None, n, "network") for n in _names(
        "Dial DialIP DialTCP DialTimeout DialUDP DialUnix FileConn FileListener "
        "FilePacketConn InterfaceAddrs InterfaceByIndex InterfaceByName Interfaces Listen "
        "ListenIP ListenMulticastUDP ListenPacket ListenTCP ListenUDP ListenUnix "
        "ListenUnixgram LookupAddr LookupCNAME LookupHost LookupIP LookupMX LookupNS "
        "LookupPort LookupSRV LookupTXT")]
    t += [("net", "Dialer", n, "network") for n in _names(
        "Dial DialContext DialIP DialTCP DialUDP DialUnix")]
    t += [("net", "Resolver", n, "network") for n in _names(
        "LookupAddr LookupCNAME LookupHost LookupIP LookupIPAddr LookupMX LookupNS "
        "LookupNetIP LookupPort LookupSRV LookupTXT")]
    t += [("net", "ListenConfig", n, "network") for n in _names("Listen ListenPacket")]
    t += [("net/http", None, n, "network") for n in _names(
        "Get Head Post PostForm ListenAndServe ListenAndServeTLS Serve ServeTLS")]
    t += [("net/http", "Client", "Do", "network"),
          ("net/http", "Transport", "RoundTrip", "network")]
    t += [("crypto/tls", None, n, "network") for n in _names("Dial DialWithDialer Listen")]
    seen, out = set(), []
    for item in t:
        key = item[:3]
        if key not in seen:
            seen.add(key)
            out.append(item)
    return out


