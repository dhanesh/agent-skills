#!/usr/bin/env python3
r"""io_guard_go.py -- the tier-aware runtime I/O guard for test-safety-net, Go.

This is the SOLE enforcement of the skill's headline invariant, "never writes
a test that performs real I/O", on the Go stack. `stack_go.py`'s triage is a
FILTER: interface dispatch, function values and reflection make reachability
undecidable from source, so the invariant is a RUNTIME property or nothing.

DOCUMENTED COMMAND -- copy the whole block. The tier travels by environment
variable, the same contract `io_guard.py` and `io_guard.js` read, and nothing
is written into the target repo, so Invariant 1 holds with no carve-out:

    TEST_SAFETY_NET_TIER=1 \
      python3 "$SKILL_DIR/assets/io_guard_go.py" \
      -run '^<test_name>$' <package>

    TEST_SAFETY_NET_TIER=2 TEST_SAFETY_NET_ALLOW=filesystem,clock \
      python3 "$SKILL_DIR/assets/io_guard_go.py" \
      -run '^<test_name>$' <package>

Everything after the script name is handed to `go test` unchanged, except
that `-count` is forced to 1 and `-overlay` is refused (both below).
`assets/test_io_guard_go.py` extracts those two commands from this header and
from every markdown file in the skill and runs them verbatim, in both
directions, so what is printed here is what is proved to work.

THE EXIT STATUS IS THE WHOLE PROTOCOL
-------------------------------------
    0  GREEN        the selected test ran and passed
    1  RED          the selected test ran and failed an assertion
    2  NOT ARMED    the guard could not arm; NOTHING was proved
    3  GUARD TRIP   IOGuardViolation: the CLASSIFICATION is wrong --
                    reclassify the unit to Tier 3 and discard the test,
                    whether the run was red or green
    4  NO TEST      nothing was proved: `-run` matched nothing, the package
                    has no test files, or the test skipped itself
    5  NO BUILD     the package did not build; a compile error is not RED

Node had to learn that per-test lines lie about asynchronous violations. Here
there is nothing to misread: a trip ENDS THE PROCESS.

HOW IT WORKS
------------
`go test` compiles before it runs, so there is no live object graph to patch
the way the python and node guards patch theirs. What there is instead is
`-overlay`: a JSON map that replaces source files in the build without
touching them on disk -- the standard library's included. So every run:

  1. lists this toolchain's own sources (`go list -e -json`), so the choice
     of per-GOOS/GOARCH files is Go's, not a table's;
  2. injects one line at the top of each I/O primitive -- every classified
     `syscall` function, the `internal/syscall/unix` *at and resolver
     families, `time`'s clock entry points, the global `math/rand` sources,
     `crypto/internal/sysrand`, `database/sql.Open`, and the `net`,
     `net/http` and `crypto/tls` entry points;
  3. adds the decision engine to package `syscall`, and a one-line forwarder
     to every other hooked package;
  4. runs `go test -overlay <map> -count=1 -vet=off -v ...`. `-vet=off`
     because `go vet` on Go 1.22-1.23 does not honour an overlay's ADDED
     files and failed every run there; vet is a lint, not part of a proof.
     `-v` because GREEN needs a `--- PASS:` line to point at.

A cold build of the overlaid standard library took 5s on go 1.26.7; a warm
one 0s -- the build cache keys on content, not path, so the overlay can live
in a fresh temporary directory every run. Tier and allow reach the engine by
environment, never baked into the source, so every tier shares one build.

THE DECISION RULE -- CALL PROVENANCE, AS IN io_guard.js
------------------------------------------------------
A hook fires on every call, including the standard library's calls on its
own behalf -- `testing` reads the clock around every test. The engine walks
`runtime.Callers` from the innermost frame outward:

  * a standard-library frame is TRANSPARENT (`go list std`, baked in); the
    walk remembers the last one it passed -- the ENTRY, the function the
    code under test actually called;
  * a frame in package `main` whose file is `_testmain.go` is the runner
    `go test` generates: EXEMPT. BELT-AND-BRACES, measured: every hooked
    call `main.main` makes today passes through `testing.(*M).Run` first,
    which the next rule already exempts, so removing this line alone leaves
    the suite green and only removing both turns the clean test red. It
    stays because the file is generated by `go test`, not by this skill, and
    a release that reached a hook from `main.main` through
    `testing/internal/testdeps` -- std, but not `testing` -- would pass
    through no rule but this one;
  * a frame in package `testing` that is NOT one of its controls means the
    runner is doing its OWN work on the test's behalf -- reporting a
    failure, timing a test -- and the call is EXEMPT. This is what measured
    into existence: `t.Fatal` reaches `runtime.Goexit`, which runs
    `tRunner`'s deferred `time.Since` with `Fatal <- TestX` still beneath
    it, so without this every RED run of the proof loop tripped as `clock`.
    What it cannot exempt is repo code: a repo `defer` doing I/O during a
    panic, a `t.Cleanup` closure and a subtest body all put a repo frame
    INNERMOST, before any testing frame is reached;
  * the first other frame -- the repo's code, or a third-party module, which
    is treated as the repo's the way io_guard.js treats node_modules -- is
    ATTRIBUTABLE, and the call is judged there;
  * reaching the end of the stack means THIS GOROUTINE holds no repo frame,
    and it is judged by the function that CREATED it -- the "created by"
    line `runtime.Stack` appends. A stdlib or generated-runner creator is the
    runtime doing its own work: EXEMPT. Any other creator is ATTRIBUTABLE.
    Review forced this: the rule used to exempt every such stack, and
    `go http.ListenAndServe(...)` in a unit bound a real port under a GREEN
    proof, because the compiler's wrapper for a `go` statement is hidden
    from runtime.Callers and the goroutine's stack is all stdlib;
  * the walk reads the WHOLE stack, growing its buffer as it goes. A fixed
    64-frame buffer read its cut-off tail as "end of stack" and exempted a
    40-level recursive template reading the environment.

Provenance reads a frame's PACKAGE PATH (`runtime.Frame.Function`), never
its file path, which `-trimpath` rewrites.

A call is blocked when the primitive's group is blocked, OR the entry's.
`net.Dial` reads the clock before it opens a socket; judged by the primitive
alone, a dial trips as `clock` -- and at tier 2 with clock allowed it would
trip later, at the socket, correctly but for the wrong reason at the wrong
moment. The entry says `network`. Testing CONTROLS override rather than add:
`t.TempDir()` reads TMPDIR on its way to the filesystem, and is the tier-2
filesystem control, so an entry of `testing.(*common).TempDir` means
filesystem alone.

A trip writes `IOGuardViolation: ...` to fd 2 and calls `syscall.Exit(3)`.
That is not a panic, so `recover()` cannot swallow it, and it ends the
process from any goroutine -- the two properties the python guard needed a
BaseException subclass and a thread hook to approximate, and the node guard
an exit-time backstop.

RESIDUALS, STATED RATHER THAN IMPLIED
-------------------------------------
1. Anything that bypasses package `syscall` is unseen: a raw syscall through
   `golang.org/x/sys/unix`, cgo, assembly. The filter declines the raw and
   cgo shapes statically; a third-party library doing it internally escapes
   both layers.
2. Standard-library work on a goroutine the standard library started ITSELF
   -- whose creator is stdlib, and whose stack holds no repo frame -- is
   exempt. A goroutine the UNIT started is judged by its creator, so
   `go http.ListenAndServe(...)` trips; what stays open is, say, the
   per-connection goroutines a stdlib server spawns. The `net/http` entry
   points are hooked on the caller's goroutine for the case that matters.
   A dependency's import-time I/O trips too, and is reported as the
   dependency's, not as a verdict on the unit.
3. Hook targets are found by text in THIS toolchain's sources. A release that
   renames a required one makes this exit 2; an optional one missing is
   recorded, not fatal.
4. `time.Sleep` has no Go body (it is linknamed to the runtime), so it is not
   hooked; a unit that only sleeps passes tier 1. `os.Args` is a variable the
   runtime fills before `main`, so reading it calls nothing a hook could sit
   in. The filter marks both; the guard sees neither.
5. Map iteration order, `select` choice and goroutine scheduling are
   nondeterminism no hook can see. A characterization test must not pin them.
6. darwin and linux only. Anything else exits 2 rather than running unarmed.
"""
