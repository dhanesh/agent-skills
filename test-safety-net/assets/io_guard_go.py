def _go_str(s):
    return json.dumps(s)


def _engine_source(std):
    return (_ENGINE
            .replace("__STD__", ", ".join(_go_str(p) for p in sorted(std)))
            .replace("__ENTRY__", ", ".join("{%s, %s}" % (_go_str(p), _go_str(g))
                                            for p, g in ENTRY_GROUPS))
            .replace("__CONTROLS__", ", ".join("%s: %s" % (_go_str(k), _go_str(v))
                                               for k, v in sorted(TESTING_CONTROLS.items()))))


# ── Building the overlay ─────────────────────────────────────────────────

def _go(go, args, env, cwd=None):
    proc = subprocess.run([go, *args], env=env, cwd=cwd, capture_output=True, text=True,
                          timeout=300, stdin=subprocess.DEVNULL)
    return proc.returncode, proc.stdout, proc.stderr


def _list_packages(go, env, pkgs):
    """path -> {"Dir", "GoFiles", "Name"} for each package this toolchain has."""
    code, out, err = _go(go, ["list", "-e", "-json", *pkgs], env)
    if code != 0 and not out.strip():
        raise GuardCannotArm("`go list` failed: %s" % (err.strip().splitlines() or ["?"])[-1])
    decoder, i, found = json.JSONDecoder(), 0, {}
    out = out.strip()
    while i < len(out):
        obj, end = decoder.raw_decode(out, i)
        i = end
        while i < len(out) and out[i].isspace():
            i += 1
        if obj.get("Error") or not obj.get("GoFiles"):
            continue
        found[obj["ImportPath"]] = obj
    return found


def build_overlay(go, env, dest):
    """(overlay JSON path, report) for this toolchain. Raises GuardCannotArm."""
    pkgs = sorted({p for p, _r, _n, _g in HOOK_TARGETS})
    listing = _list_packages(go, env, pkgs)
    code, std_out, err = _go(go, ["list", "std"], env)
    std = [line.strip() for line in std_out.splitlines() if line.strip()]
    if code != 0 or "syscall" not in std:
        raise GuardCannotArm("`go list std` failed: %s" % (err.strip() or "no output"))

    sources, hooked_pkgs = {}, set()
    report = {"hooked": [], "skipped": []}
    for pkg, recv, name, group in HOOK_TARGETS:
        label = "%s.%s" % (pkg, name if recv is None else "(*%s).%s" % (recv, name))
        required = (pkg, recv, name) in REQUIRED_TARGETS
        info = listing.get(pkg)
        if info is None:
            if required:
                raise GuardCannotArm("package %s is not in this toolchain" % pkg)
            report["skipped"].append((label, "package not in this toolchain"))
            continue
        if group == "stdin":
            stmt = 'if fd == 0 { tsnHook("stdin", "%s(0)") }' % label
        else:
            stmt = 'tsnHook("%s", "%s")' % (group, label)
        done = False
        for fname in info["GoFiles"]:
            path = os.path.join(info["Dir"], fname)
            if path not in sources:
                with open(path, encoding="utf-8") as f:
                    sources[path] = f.read()
            if group == "stdin" and not re.search(r"(?m)^func %s\(fd int," % name, sources[path]):
                continue
            try:
                new = inject(sources[path], name, stmt, recv)
            except KeyError:
                continue
            done = True
            if new is None:
                if required:
                    raise GuardCannotArm("%s has no Go body in this toolchain" % label)
                report["skipped"].append((label, "no Go body"))
            else:
                sources[path] = new
                hooked_pkgs.add(pkg)
                report["hooked"].append(label)
            break
        if not done:
            if required:
                raise GuardCannotArm("required hook target %s not found in this toolchain's "
                                     "sources" % label)
            report["skipped"].append((label, "not found in this toolchain"))
    if "syscall" not in hooked_pkgs:
        raise GuardCannotArm("no syscall function could be hooked")

    replace = {}
    for n, (path, text) in enumerate(sorted(sources.items())):
        if not any(path.startswith(os.path.join(listing[p]["Dir"], "")) for p in hooked_pkgs):
            continue
        out_path = os.path.join(dest, "%03d_%s" % (n, os.path.basename(path)))
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(text)
        replace[path] = out_path
    for pkg in sorted(hooked_pkgs):
        info = listing[pkg]
        text = (_engine_source(std) if pkg == "syscall"
                else _FORWARDER % info.get("Name", os.path.basename(pkg)))
        out_path = os.path.join(dest, "zz_tsn_%s.go" % pkg.replace("/", "_"))
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(text)
        replace[os.path.join(info["Dir"], "zz_tsn_hook.go")] = out_path
    overlay = os.path.join(dest, "overlay.json")
    with open(overlay, "w", encoding="utf-8") as f:
        json.dump({"Replace": replace}, f)
    return overlay, report


# ── Running ──────────────────────────────────────────────────────────────

def _asks_for_overlay(args):
    return any(a == "-overlay" or a.startswith("-overlay=") or a == "--overlay"
               or a.startswith("--overlay=") for a in args)


def _say(msg):
    sys.stderr.write(_PREFIX + msg + "\n")
    sys.stderr.flush()


def _not_armed(why):
    _say("NOT ARMED (exit 2): %s. Nothing was proved; fix the environment and re-run." % why)
    return EXIT_NOT_ARMED


def classify(code, out, overlay_dir):
    """The exit status for one `go test -v` run, from its code and its output.

    GREEN needs positive evidence: a `--- PASS:` line and no `--- SKIP:` one.
    It used to be "exit 0 and no `no tests to run`", and review found two more
    ways for `go test` to exit 0 having proved nothing -- a package with no
    `_test.go` files (`? pkg [no test files]`) and a test that calls `t.Skip`.
    Both read as GREEN, and a pinned test that skips itself would have been
    kept. Requiring the PASS line also stops a `./...` run whose other package
    printed `[no tests to run]` from reading as NO TEST.
    """
    if "IOGuardViolation" in out:
        return EXIT_TRIP
    if overlay_dir and (overlay_dir in out or "zz_tsn_" in out) and code != 0:
        return EXIT_NOT_ARMED
    if "[build failed]" in out or "[setup failed]" in out:
        return EXIT_NO_BUILD
    if code != 0:
        return EXIT_RED
    if "--- SKIP:" in out or "--- PASS:" not in out:
        return EXIT_NO_TEST
    return EXIT_GREEN


def _strip_count(args):
    """`args` without any `-count` -- both `-count=N` and the split `-count N`."""
    out, skip = [], False
    for a in args:
        if skip:
            skip = False
            continue
        if a in ("-count", "--count"):
            skip = True
            continue
        if a.startswith(("-count=", "--count=")):
            continue
        out.append(a)
    return out


def _main_modules(go, env):
    """The module path(s) under test, for telling the repo's code from a dependency's."""
    code, out, _err = _go(go, ["list", "-m", "-f", "{{.Path}}"], env, cwd=os.getcwd())
    return [line.strip() for line in out.splitlines() if line.strip()] if code == 0 else []


