#!/usr/bin/env python3
"""skill_graph.py: render and check the "who calls whom" diagrams of this repo.

One data file, docs/skill-graph/graph.json, says which skill calls which, when and
why. This script renders it as mermaid diagrams between marker comments:

  - the root README.md gets one overview, grouped by stage (inserted before the
    heading named by `root_insert_before` the first time);
  - each <skill>/README.md gets a small diagram with the skill in the middle, its
    callers on the left and its callees on the right (inserted before the first
    `## ` heading the first time).

    <!-- skill-graph:start -->  ...generated...  <!-- skill-graph:end -->

Usage:
  python3 skill_graph.py --write [--root DIR]   # validate the data, then (re)write blocks
  python3 skill_graph.py --check [--root DIR]   # validate the data and compare blocks

The data rules (`--check` fails on any of them):

  nodes     Every top-level dir with a SKILL.md is a node, and every node is such a dir.
            A node has `stage` (one of `stages`), `role` (`entry`: a human usually
            starts here; `called`: usually reached from another skill, so it needs at
            least one caller), `start` (the "Start here if ..." clause) and `use_when`
            ({"file": "<node>/SKILL.md", "quote": "<words>"}: a quote, matched as
            for evidence below, on a line that says "use when"). A node in
            the `alone` stage has no edges; a node with no edges is in `alone`.
  edges     `from` -> `to` means `from` sends work or data to `to` (producer ->
            consumer). One edge per ordered pair. `kind` is one of:
              contract  a skill-contract envelope goes from `from` to `to`;
              required  a step of `from` runs `to`, or needs it first;
              handoff   `from` sends its result to `to`; a human starts `to` next;
              optional  `from` uses `to` only when it is installed.
            `short` (root label), `when` and `why` (per-skill label) are plain text.
  evidence  Each item is {"file": "<skill>/<file>", "quote": "<words>", "mentions": "<skill>"}.
            The file belongs to one end of the edge and `mentions` is the other end.
            `quote` is a short verbatim run of words from the file (6-15 words is a
            good size). Runs of whitespace, line breaks too, count as one space, so a
            line that moves or a paragraph that is rewrapped does not break it. The
            quote starts and ends on a word boundary, occurs exactly once in the file, and the line(s) it spans name
            `mentions`. A file under references/ is linked from that skill's
            SKILL.md. Every non-contract edge has at least one item.
  contract  The contract edges are exactly the pairs where `from`'s
            ```json skill-contract block provides a kind that `to`'s block consumes,
            and `envelopes` lists those kinds (`task-plan/v1`, ...).

Prints PASS:/FAIL: lines and a final SKILL_GRAPH_RESULT: PASS | FAIL (n) line.
Stdlib only; no network.
"""
from __future__ import annotations

import argparse
import bisect
import json
import os
import re
import sys

START = "<!-- skill-graph:start -->"
END = "<!-- skill-graph:end -->"
GRAPH = os.path.join("docs", "skill-graph", "graph.json")
NOTE = ("<!-- Generated by scripts/gates/skill_graph.py from docs/skill-graph/graph.json. "
        "Do not edit this block by hand: edit the JSON, then run `make skill-graph`. -->")
KINDS = ("contract", "required", "handoff", "optional")
ARROW = {"contract": "==>", "required": "-->", "handoff": "--o", "optional": "-.->"}
ROLES = ("entry", "called")
CONTRACT_PREFIX = "https://github.com/dhanesh/agent-skills/skill-contract/"
# Characters that break or confuse a mermaid label, even inside quotes.
UNSAFE = re.compile(r'["|\[\]{}()<>#;`\\]')
LEGEND = [
    "- `==>` thick arrow, **contract**: a skill-contract envelope (a typed, checked file) goes to the next skill.",
    "- `-->` solid arrow, **required**: a step runs the next skill, or needs it first.",
    "- `--o` circle end, **handoff**: the result goes to the next skill, and you start that skill.",
    "- `-.->` dashed arrow, **optional**: used only when you install the next skill.",
]


class Fail(Exception):
    pass


def skills_in(root: str) -> list[str]:
    return sorted(d for d in os.listdir(root)
                  if not d.startswith(".") and os.path.isfile(os.path.join(root, d, "SKILL.md")))


def nid(prefix: str, name: str) -> str:
    return prefix + name.replace("-", "_")


def name_re(name: str) -> re.Pattern:
    return re.compile(r"(?<![\w-])" + re.escape(name) + r"(?![\w-])")


def contract_blocks(root: str, skills: list[str]) -> dict[str, dict]:
    out = {}
    pat = re.compile(r"^```json skill-contract\n(.*?)\n```", re.M | re.S)
    for s in skills:
        with open(os.path.join(root, s, "SKILL.md"), encoding="utf-8") as fh:
            m = pat.search(fh.read())
        if not m:
            continue
        data = json.loads(m.group(1))
        short = lambda urls: sorted(u[len(CONTRACT_PREFIX):] if u.startswith(CONTRACT_PREFIX) else u for u in urls)
        out[s] = {"provides": short(data.get("provides", [])), "consumes": short(data.get("consumes", []))}
    return out


# ── validation ────────────────────────────────────────────────────────────────

def validate(root: str, g: dict) -> list[str]:
    """Return a list of FAIL messages (empty when the data is sound)."""
    fails: list[str] = []
    skills = skills_in(root)
    nodes = g.get("nodes", {})
    stages = [s["id"] for s in g.get("stages", [])]
    edges = g.get("edges", [])

    for s in skills:
        if s not in nodes:
            fails.append(f"skill {s} is missing from {GRAPH} (add a node)")
    for n in nodes:
        if n not in skills:
            fails.append(f"graph node {n} is not a skill directory (no {n}/SKILL.md)")

    linked = {e["from"] for e in edges} | {e["to"] for e in edges}
    for n, d in sorted(nodes.items()):
        if d.get("stage") not in stages:
            fails.append(f"node {n}: stage {d.get('stage')!r} is not one of {stages}")
        if d.get("role") not in ROLES:
            fails.append(f"node {n}: role {d.get('role')!r} is not one of {list(ROLES)}")
        start = d.get("start", "")
        if not start or UNSAFE.search(start):
            fails.append(f"node {n}: `start` is empty or has a character mermaid cannot carry")
        if n in skills:
            fails.extend(check_use_when(root, n, d.get("use_when")))
        if (d.get("stage") == "alone") != (n not in linked):
            fails.append(f"node {n}: a node is in stage 'alone' exactly when it has no edges")
        if d.get("role") == "called" and not any(e["to"] == n for e in edges):
            fails.append(f"node {n}: role 'called' needs at least one caller")

    seen = set()
    for e in edges:
        a, b, k = e.get("from"), e.get("to"), e.get("kind")
        tag = f"edge {a} -> {b}"
        if a not in nodes or b not in nodes or a == b:
            fails.append(f"{tag}: both ends must be distinct graph nodes")
            continue
        if (a, b) in seen:
            fails.append(f"{tag}: duplicate pair (merge the kinds into one edge)")
        seen.add((a, b))
        if k not in KINDS:
            fails.append(f"{tag}: kind {k!r} is not one of {list(KINDS)}")
        for f, cap in (("short", 28), ("when", 70), ("why", 70)):
            v = e.get(f, "")
            if not v or len(v) > cap or UNSAFE.search(v):
                fails.append(f"{tag}: `{f}` must be 1-{cap} chars with none of \" | [ ] {{ }} ( ) < > # ; ` \\")
        ev = e.get("evidence", [])
        if k != "contract" and not ev:
            fails.append(f"{tag}: a {k} edge needs at least one evidence line")
        for item in ev:
            fails.extend(check_evidence(root, tag, a, b, item))

    # Contract edges are exactly the provides/consumes pairs.
    blocks = contract_blocks(root, [s for s in skills])
    derived: dict[tuple[str, str], list[str]] = {}
    for p, pb in blocks.items():
        for c, cb in blocks.items():
            if p == c:
                continue
            kinds = sorted(set(pb["provides"]) & set(cb["consumes"]))
            if kinds:
                derived[(p, c)] = kinds
    declared = {(e["from"], e["to"]): sorted(e.get("envelopes", []))
                for e in edges if e.get("kind") == "contract"}
    for pair, kinds in sorted(derived.items()):
        if pair not in declared:
            fails.append(f"contract pair {pair[0]} -> {pair[1]} ({', '.join(kinds)}) has no contract edge")
        elif declared[pair] != kinds:
            fails.append(f"contract edge {pair[0]} -> {pair[1]}: envelopes {declared[pair]} but the blocks say {kinds}")
    for pair in sorted(declared):
        if pair not in derived:
            fails.append(f"contract edge {pair[0]} -> {pair[1]}: no skill-contract block provides what the other consumes")
    for e in edges:
        if e.get("kind") != "contract" and e.get("envelopes"):
            fails.append(f"edge {e['from']} -> {e['to']}: only a contract edge carries `envelopes`")
    return fails


MIN_QUOTE_WORDS = 3


def normalise(text: str) -> tuple[str, list[int], list[int]]:
    """Collapse each run of whitespace to one space.

    Return the joined text, the offset of each word in it, and the 1-based
    line number of each word in the original text.
    """
    norm: list[str] = []
    offs: list[int] = []
    lines: list[int] = []
    pos = 0
    for n, line in enumerate(text.split("\n"), 1):
        for w in line.split():
            offs.append(pos)
            lines.append(n)
            norm.append(w)
            pos += len(w) + 1
    return " ".join(norm), offs, lines


def find_all(hay: str, needle: str) -> list[int]:
    """Every start of `needle` in `hay` that begins and ends on a word boundary,
    so "closes the" does not match inside "encloses the"."""
    out, i = [], hay.find(needle)
    while i != -1:
        j = i + len(needle)
        cut_in = i > 0 and hay[i - 1].isalnum() and needle[0].isalnum()
        cut_out = j < len(hay) and hay[j].isalnum() and needle[-1].isalnum()
        if not (cut_in or cut_out):
            out.append(i)
        i = hay.find(needle, i + 1)
    return out


def locate(root: str, path: str, quote: str, says: re.Pattern, what: str) -> str | None:
    """Find `quote` in the file at `path` and check that the line(s) it spans match
    `says`. Return None when it does, else the reason it does not (`what` names
    the thing `says` looks for, in the message)."""
    q = " ".join(quote.split())
    if len(q.split(" ")) < MIN_QUOTE_WORDS:
        return f"{path} needs a `quote` of at least {MIN_QUOTE_WORDS} words"
    with open(os.path.join(root, path), encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    norm, offs, wline = normalise(text)
    lines = text.split("\n")
    now = [str(n) for n, l in enumerate(lines, 1) if says.search(l)]
    where = (f"{what} is now on line(s) {', '.join(now[:8])}" if now
             else f"the file no longer has {what}")
    hits = find_all(norm, q)

    def span(i: int) -> tuple[int, int]:
        first = bisect.bisect_right(offs, i) - 1
        last = bisect.bisect_right(offs, i + len(q) - 1) - 1
        return wline[first], wline[last]

    if not hits:
        return f"quote {quote!r} is not in {path}; {where}"
    if len(hits) > 1:
        at = ", ".join(str(span(i)[0]) for i in hits[:8])
        return (f"quote {quote!r} occurs {len(hits)} times in {path} "
                f"(lines {at}); use a longer quote")
    lo, hi = span(hits[0])
    if says.search("\n".join(lines[lo - 1:hi])):
        return None
    lref = f"line {lo}" if lo == hi else f"lines {lo}-{hi}"
    return f"quote {quote!r} in {path} ({lref}) no longer sits on a line that has {what}; {where}"


USE_WHEN = re.compile(r"use\s+when", re.I)


def check_use_when(root: str, n: str, item) -> list[str]:
    if not isinstance(item, dict) or set(item) != {"file", "quote"}:
        return [f"node {n}: use_when must be {{\"file\": \"{n}/SKILL.md\", \"quote\": \"...\"}}, not {item!r}"]
    if item["file"] != f"{n}/SKILL.md":
        return [f"node {n}: use_when file {item['file']!r} is not {n}/SKILL.md"]
    if not os.path.isfile(os.path.join(root, item["file"])):
        return []  # the missing skill is reported on its own
    why = locate(root, item["file"], item.get("quote", ""), USE_WHEN, "'use when'")
    return [f"node {n}: use_when {why}"] if why else []


def check_evidence(root: str, tag: str, a: str, b: str, item: dict) -> list[str]:
    path, want, quote = item.get("file", ""), item.get("mentions", ""), item.get("quote", "")
    if "at" in item:
        return [f"{tag}: evidence {item['at']!r} uses the old `at` field; "
                f"give `file` and a verbatim `quote` instead"]
    owner = path.split("/", 1)[0]
    if owner not in (a, b) or "/" not in path:
        return [f"{tag}: evidence file {path!r} must be <one end>/<file>"]
    other = b if owner == a else a
    if want != other:
        return [f"{tag}: evidence in {path} must mention {other}, not {want!r}"]
    full = os.path.join(root, path)
    if not os.path.isfile(full):
        return [f"{tag}: evidence file {path} does not exist"]
    if "/references/" in path:
        rel = path.split("/", 1)[1]
        with open(os.path.join(root, owner, "SKILL.md"), encoding="utf-8") as fh:
            if rel not in fh.read():
                return [f"{tag}: {path} is not linked from {owner}/SKILL.md"]
    why = locate(root, path, quote, name_re(want), want)
    return [f"{tag}: evidence {why}"] if why else []


# ── rendering ─────────────────────────────────────────────────────────────────

def label_full(e: dict) -> str:
    parts = [f"when: {e['when']}", f"why: {e['why']}"]
    if e["kind"] == "contract":
        parts.append("envelope: " + ", ".join(e["envelopes"]))
    return "<br/>".join(parts)


def render_root(g: dict) -> str:
    nodes, edges = g["nodes"], g["edges"]
    out = [START, "## How the skills fit together", "", NOTE, ""]
    out += [p for s in g.get("where_to_start", []) for p in (s, "")]
    out += ["```mermaid", "flowchart TB"]
    for st in g["stages"]:
        members = sorted(n for n, d in nodes.items() if d["stage"] == st["id"])
        if not members or st["id"] == "alone":
            continue
        out.append(f'  subgraph st_{st["id"]}["{st["title"]}"]')
        out.append("    direction TB")
        out += [f'    {nid("s_", n)}["{n}"]' for n in members]
        out.append("  end")
    for e in sorted(edges, key=lambda e: (KINDS.index(e["kind"]), e["from"], e["to"])):
        out.append(f'  {nid("s_", e["from"])} {ARROW[e["kind"]]}|"{e["short"]}"| {nid("s_", e["to"])}')
    entries = sorted(n for n, d in nodes.items() if d["role"] == "entry" and d["stage"] != "alone")
    if entries:
        out.append("  classDef entry stroke-width:3px")
        out.append("  class " + ",".join(nid("s_", n) for n in entries) + " entry")
    out.append("```")
    out += ["", "How to read it. An arrow from A to B means A sends work or data to B.", ""]
    out += LEGEND
    alone = sorted(n for n, d in nodes.items() if d["stage"] == "alone")
    out.append("- A thick border marks a good place to start.")
    out.append("")
    linked = len(nodes) - len(alone)
    line = f"The diagram shows the {linked} linked skills and all {len(edges)} links."
    if alone:
        line += (f" It leaves out {len(alone)} skills that work alone: {code_list(alone)}. "
                 "They call no skill, and no skill calls them.")
    out += [line, "",
            "Each skill's README has a smaller diagram with its own callers and callees, and the full when and why of each link.",
            END]
    return "\n".join(out)


def callers_callees(g: dict, n: str) -> tuple[list[dict], list[dict]]:
    ins = sorted((e for e in g["edges"] if e["to"] == n), key=lambda e: e["from"])
    outs = sorted((e for e in g["edges"] if e["from"] == n), key=lambda e: e["to"])
    return ins, outs


def code_list(names: list[str]) -> str:
    q = [f"`{x}`" for x in names]
    return q[0] if len(q) == 1 else ", ".join(q[:-1]) + " and " + q[-1]


def render_skill(g: dict, n: str) -> str:
    d = g["nodes"][n]
    ins, outs = callers_callees(g, n)
    out = [START, "## Where it fits", "", NOTE, ""]
    if not ins and not outs:
        out.append(f"**Works alone.** No other skill in this repo calls it, and it calls none. "
                   f"Start here if {d['start']}.")
    else:
        main = [e["from"] for e in ins if e["kind"] != "optional"]
        extra = [e["from"] for e in ins if e["kind"] == "optional"]
        if d["role"] == "called" and not main:
            main, extra = extra, []
        also = ""
        if extra:
            verb = "uses" if len(extra) == 1 else "use"
            also = f" {code_list(extra)} also {verb} it when it is installed."
        if d["role"] == "entry":
            line = f"**Start here if** {d['start']}."
            if main:
                line += f" Other skills also send work here: {code_list(main)}."
            out.append(line + also)
        else:
            out.append(f"**Usually called by** {code_list(main)}.{also} "
                       f"You can also start it yourself when {d['start']}.")
    out += ["", "```mermaid", "flowchart LR"]
    if ins:
        out += ['  subgraph callers["Called by"]', "    direction TB"]
        out += [f'    {nid("in_", e["from"])}["{e["from"]}"]' for e in ins]
        out.append("  end")
    out.append(f'  {nid("self_", n)}["{n}"]')
    if outs:
        out += ['  subgraph callees["Calls"]', "    direction TB"]
        out += [f'    {nid("out_", e["to"])}["{e["to"]}"]' for e in outs]
        out.append("  end")
    for e in ins:
        out.append(f'  {nid("in_", e["from"])} {ARROW[e["kind"]]}|"{label_full(e)}"| {nid("self_", n)}')
    for e in outs:
        out.append(f'  {nid("self_", n)} {ARROW[e["kind"]]}|"{label_full(e)}"| {nid("out_", e["to"])}')
    out.append("  classDef self stroke-width:4px,font-weight:bold")
    out.append(f"  class {nid('self_', n)} self")
    out.append("```")
    if not ins and not outs:
        out += ["", "The map of all skills is in the [root README](../README.md#how-the-skills-fit-together).", END]
        return "\n".join(out)
    out += ["", "An arrow from A to B means A sends work or data to B. "
                "`==>` contract envelope, `-->` required, `--o` handoff (you start the next skill), "
                "`-.->` optional (only when installed). "
                "The map of all skills is in the [root README](../README.md#how-the-skills-fit-together).",
            END]
    return "\n".join(out)


# ── block I/O ─────────────────────────────────────────────────────────────────

def find_block(text: str) -> tuple[int, int] | None:
    if text.count(START) != 1 or text.count(END) != 1:
        return None
    s, e = text.index(START), text.index(END)
    if e < s:
        return None
    return s, e + len(END)


def insert_block(text: str, block: str, before: str | None) -> str:
    lines = text.split("\n")
    idx = None
    for i, l in enumerate(lines):
        if (before is not None and l.strip() == before) or (before is None and l.startswith("## ")):
            idx = i
            break
    if idx is None:
        return text.rstrip("\n") + "\n\n" + block + "\n"
    return "\n".join(lines[:idx] + [block, ""] + lines[idx:])


def targets(root: str, g: dict) -> list[tuple[str, str, str | None]]:
    out = [(os.path.join(root, "README.md"), render_root(g), g.get("root_insert_before"))]
    for n in sorted(g["nodes"]):
        out.append((os.path.join(root, n, "README.md"), render_skill(g, n), None))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    root = os.path.abspath(args.root)

    try:
        with open(os.path.join(root, GRAPH), encoding="utf-8") as fh:
            g = json.load(fh)
    except (OSError, ValueError) as exc:
        print(f"FAIL: cannot read {GRAPH}: {exc}")
        print("SKILL_GRAPH_RESULT: FAIL (1)")
        return 1

    fails = validate(root, g)
    if fails:
        for f in fails:
            print(f"FAIL: {f}")
        print(f"SKILL_GRAPH_RESULT: FAIL ({len(fails)})")
        return 1
    print(f"PASS: {GRAPH} matches the skills ({len(g['nodes'])} nodes, {len(g['edges'])} edges)")

    for path, block, before in targets(root, g):
        rel = os.path.relpath(path, root)
        if not os.path.isfile(path):
            fails.append(f"{rel} does not exist")
            continue
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        span = find_block(text)
        if args.write:
            new = text[:span[0]] + block + text[span[1]:] if span else insert_block(text, block, before)
            if new != text:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)
                print(f"WROTE: {rel}")
        elif span is None:
            fails.append(f"{rel} has no single {START} ... {END} block (run `make skill-graph`)")
        elif text[span[0]:span[1]] != block:
            fails.append(f"{rel}: the skill-graph block differs from {GRAPH} (run `make skill-graph`)")
        else:
            print(f"PASS: {rel} block is current")

    for f in fails:
        print(f"FAIL: {f}")
    if fails:
        print(f"SKILL_GRAPH_RESULT: FAIL ({len(fails)})")
        return 1
    print("SKILL_GRAPH_RESULT: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
