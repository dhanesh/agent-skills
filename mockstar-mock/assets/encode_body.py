#!/usr/bin/env python3
"""Compress, decode and verify mock response bodies; emit encoded-response handlers.

Why: mockstar static responses and scenarios carry text or JSON only, so a
`Content-Encoding` response needs a dynamic handler that returns raw bytes
(see references/mockstar-mapping.md, "Encoded responses"). This helper makes
those bytes at generation time. Stdlib only.

Subcommands:
  encode  --encoding gzip|deflate --body-file F [--out F]
          Write the compressed bytes (stdout when --out is absent).
  decode  --encoding gzip|deflate|br --in F
          Write the decoded bytes to stdout.
  verify  --encoding E --raw F --expected F
          Exit 0 when decode(raw) equals the expected plain body.
  handler --name N --encoding E --body-file F [--status 200]
          [--content-type T] [--header NAME=VALUE ...] [--out F]
          Print a TypeScript handler for mockstar's handlers/ directory.

Exit codes: 0 ok, 1 mismatch, 2 bad input, 5 br needs node or bun (no stdlib brotli).

br: Python has no stdlib brotli. `handler --encoding br` emits a handler that
calls node:zlib brotliCompressSync when the server loads it. `decode` and
`verify` for br call node or bun if one is on PATH, else exit 5.
"""
import argparse
import base64
import gzip
import json
import shutil
import subprocess
import sys
import zlib

ENCODINGS = ("gzip", "deflate", "br")
EXIT_NO_BROTLI = 5

_BR_DECODE_JS = (
    "const z=require('zlib');const c=[];process.stdin.on('data',d=>c.push(d));"
    "process.stdin.on('end',()=>process.stdout.write(z.brotliDecompressSync(Buffer.concat(c))));"
)


def compress(data, encoding):
    """Compress bytes. gzip uses mtime 0 so the output is reproducible."""
    if encoding == "gzip":
        return gzip.compress(data, compresslevel=9, mtime=0)
    if encoding == "deflate":
        # HTTP "deflate" is the zlib format (RFC 9110 section 8.4.1.2).
        return zlib.compress(data, 9)
    raise ValueError(f"cannot compress {encoding!r} with the stdlib")


def _brotli_runtime():
    for exe in ("node", "bun"):
        path = shutil.which(exe)
        if path:
            return path
    return None


def decompress(data, encoding):
    """Decode bytes. Raises RuntimeError for br when no node or bun exists."""
    if encoding == "gzip":
        return gzip.decompress(data)
    if encoding == "deflate":
        try:
            return zlib.decompress(data)
        except zlib.error:
            return zlib.decompress(data, -zlib.MAX_WBITS)  # raw deflate, tolerated
    if encoding == "br":
        runtime = _brotli_runtime()
        if runtime is None:
            raise RuntimeError("br decode needs node or bun on PATH")
        proc = subprocess.run([runtime, "-e", _BR_DECODE_JS], input=data,
                              capture_output=True, timeout=30)
        if proc.returncode != 0:
            raise ValueError("br decode failed: " + proc.stderr.decode("utf-8", "replace")[:200])
        return proc.stdout
    raise ValueError(f"unknown encoding {encoding!r}")


def _ts_string(text):
    return json.dumps(text)  # a JSON string literal is a valid TS string literal


def render_handler(name, encoding, body, status=200, content_type="application/json",
                   headers=None):
    """Return TypeScript source for a mockstar named handler that serves `body` encoded."""
    hdrs = {"content-type": content_type, "content-encoding": encoding,
            "vary": "Accept-Encoding"}
    for key, value in (headers or {}).items():
        hdrs[key] = value
    header_lines = ",\n".join(f"  {_ts_string(k)}: {_ts_string(v)}" for k, v in hdrs.items())
    head = (
        f"// handlers/{name}.ts — generated by mockstar-mock assets/encode_body.py\n"
        f"// Serves one fixed body with Content-Encoding: {encoding}.\n"
    )
    if encoding == "br":
        plain_b64 = base64.b64encode(body).decode("ascii")
        payload = (
            "import { brotliCompressSync } from 'node:zlib';\n\n"
            f"const PLAIN_B64 = {_ts_string(plain_b64)};\n"
            "// br has no stdlib encoder in Python, so compress once when the server loads.\n"
            "const BODY = brotliCompressSync(Buffer.from(PLAIN_B64, 'base64'));\n"
        )
    else:
        packed = base64.b64encode(compress(body, encoding)).decode("ascii")
        payload = (
            f"const BODY_B64 = {_ts_string(packed)};  // {encoding}, made at generation time\n"
            "const BODY = Buffer.from(BODY_B64, 'base64');\n"
        )
    return (
        head + "\n" + payload +
        f"\nconst HEADERS = {{\n{header_lines},\n}};\n\n"
        f"export async function {name}(): Promise<Response> {{\n"
        f"  return new Response(BODY, {{ status: {int(status)}, headers: HEADERS }});\n"
        "}\n"
    )


def _read(path):
    with open(path, "rb") as f:
        return f.read()


def _write(path, data):
    if path:
        with open(path, "wb") as f:
            f.write(data)
    else:
        sys.stdout.buffer.write(data)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("encode")
    p.add_argument("--encoding", choices=("gzip", "deflate"), required=True)
    p.add_argument("--body-file", required=True)
    p.add_argument("--out")

    p = sub.add_parser("decode")
    p.add_argument("--encoding", choices=ENCODINGS, required=True)
    p.add_argument("--in", dest="infile", required=True)

    p = sub.add_parser("verify")
    p.add_argument("--encoding", choices=ENCODINGS, required=True)
    p.add_argument("--raw", required=True)
    p.add_argument("--expected", required=True)

    p = sub.add_parser("handler")
    p.add_argument("--name", required=True)
    p.add_argument("--encoding", choices=ENCODINGS, required=True)
    p.add_argument("--body-file", required=True)
    p.add_argument("--status", type=int, default=200)
    p.add_argument("--content-type", default="application/json")
    p.add_argument("--header", action="append", default=[], metavar="NAME=VALUE")
    p.add_argument("--out")

    args = ap.parse_args(argv)
    try:
        if args.cmd == "encode":
            _write(args.out, compress(_read(args.body_file), args.encoding))
            return 0
        if args.cmd == "decode":
            _write(None, decompress(_read(args.infile), args.encoding))
            return 0
        if args.cmd == "verify":
            got = decompress(_read(args.raw), args.encoding)
            if got == _read(args.expected):
                print(f"PASS: decoded {args.encoding} body equals the expected body")
                return 0
            print(f"FAIL: decoded {args.encoding} body differs from the expected body")
            return 1
        if args.cmd == "handler":
            if not args.name.isidentifier():
                print(f"bad --name {args.name!r}: use a TypeScript identifier", file=sys.stderr)
                return 2
            extra = {}
            for item in args.header:
                key, sep, value = item.partition("=")
                if not sep or not key:
                    print(f"bad --header {item!r}: use NAME=VALUE", file=sys.stderr)
                    return 2
                extra[key.lower()] = value
            src = render_handler(args.name, args.encoding, _read(args.body_file),
                                 args.status, args.content_type, extra)
            _write(args.out, src.encode("utf-8"))
            return 0
    except RuntimeError as exc:
        print(f"SKIP: {exc}", file=sys.stderr)
        return EXIT_NO_BROTLI
    except (OSError, ValueError, zlib.error, EOFError, gzip.BadGzipFile) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    return 2


if __name__ == "__main__":
    sys.exit(main())
